CREATE TABLE erp.months (
    month_id date NOT NULL,
    year integer NOT NULL,
    quarter integer NOT NULL,
    month_number integer NOT NULL,
    days_in_month integer NOT NULL,
    PRIMARY KEY (month_id),
    CONSTRAINT ck_months_00 CHECK (year >= 0),
    CONSTRAINT ck_months_01 CHECK (quarter >= 0),
    CONSTRAINT ck_months_02 CHECK (month_number >= 0),
    CONSTRAINT ck_months_03 CHECK (days_in_month >= 0),
    CONSTRAINT ck_months_04 CHECK (month_id = date_trunc('month', month_id)::date),
    CONSTRAINT ck_months_05 CHECK (year = extract(year FROM month_id)),
    CONSTRAINT ck_months_06 CHECK (quarter = extract(quarter FROM month_id)),
